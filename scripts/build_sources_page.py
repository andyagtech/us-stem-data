#!/usr/bin/env python3
"""One page listing every source the project draws on, grouped by publisher.

The methodology page lists datasets. This lists SOURCES, which is the
question a reader actually asks: whose data is this, and where do I get it
myself? Generated from the catalogue so it cannot drift from what is
actually built.

Internal artifacts -- the site map, the assistant's bundle, the Parquet
exports -- have no external source and are listed separately rather than
hidden, so the counts reconcile.

Usage:
  python3 scripts/build_sources_page.py
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "SOURCES.md"

sys.path.insert(0, str(ROOT))
from pipeline.datasets import CATALOG                       # noqa: E402

# Publisher names as a reader would recognise them, matched against the
# source string. Order matters: the first match wins, so the more specific
# patterns come first.
PUBLISHERS = [
    (r"NSF NCSES|NCSES|National Science Foundation|NSF ", "National Science Foundation (NCSES)"),
    (r"NCES|IPEDS", "Dept. of Education (NCES / IPEDS)"),
    (r"College Scorecard|U\.S\. Department of Education", "Dept. of Education (College Scorecard)"),
    (r"US DOL|Department of Labor|Office of Foreign Labor", "Dept. of Labor"),
    (r"USCIS", "USCIS"),
    (r"DHS|SEVP|Homeland Security", "Dept. of Homeland Security"),
    # BridgeUSA is the State Department's own name for the J-1 programme,
    # and its figures are published on j1visa.state.gov.
    (r"Department of State|Visa Bulletin|BridgeUSA", "Dept. of State"),
    (r"IRS|IRC ", "IRS / Internal Revenue Code"),
    (r"World Bank", "World Bank"),
    (r"Census", "Census Bureau"),
]
THIRD_PARTY = re.compile(r"^https?://|\.com|\.org", re.I)


def publisher(d) -> str:
    src = d.source or ""
    if not src:
        return "Derived within this project"
    for pattern, name in PUBLISHERS:
        if re.search(pattern, src, re.I):
            return name
    if src.lower().startswith("derived"):
        return "Derived within this project"
    if THIRD_PARTY.search(src):
        return "Third-party (not a government source)"
    return "Other"


def main() -> int:
    groups: dict[str, list] = defaultdict(list)
    for d in CATALOG:
        groups[publisher(d)].append(d)

    internal = [d for d in CATALOG if not d.source_url]
    external = [d for d in CATALOG if d.source_url]

    lines = [
        "# Sources",
        "",
        f"Every dataset this project draws on, grouped by who publishes it. "
        f"**{len(CATALOG)} datasets**, of which **{len(external)}** come from an "
        f"outside source with a retrieval URL and **{len(internal)}** are built "
        f"here from the others.",
        "",
        "Generated by `scripts/build_sources_page.py` from `pipeline/datasets.py`. "
        "Do not edit by hand — it will be overwritten, and the catalogue is what "
        "the consistency checks read.",
        "",
        "A source URL is the page a reader goes to, not always a direct file "
        "link: several agencies serve their tables through a search interface, "
        "and two (travel.state.gov, and the DOL enforcement portal) refuse "
        "automated requests entirely, so those files were retrieved by hand.",
        "",
    ]

    order = sorted(groups, key=lambda k: (k.startswith("Derived"),
                                          k.startswith("Third-party"),
                                          -len(groups[k])))
    for name in order:
        items = sorted(groups[name], key=lambda d: d.key)
        lines += [f"## {name}", "", f"*{len(items)} dataset"
                  f"{'s' if len(items) != 1 else ''}*", ""]
        lines += ["| Dataset | What it provides | Source | Retrieve |",
                  "|---|---|---|---|"]
        for d in items:
            summary = re.sub(r"\s+", " ", d.summary or "").strip()
            if len(summary) > 118:
                summary = summary[:115].rsplit(" ", 1)[0] + "…"
            src = re.sub(r"\s+", " ", d.source or "—").strip()
            url = f"[link]({d.source_url})" if d.source_url else "—"
            lines.append(f"| `{d.key}` | {summary} | {src} | {url} |")
        lines.append("")

    # Anything held off disk has to say where it actually lives.
    archived = [d for d in CATALOG if d.archived_at]
    if archived:
        lines += ["## Held outside the repository", "",
                  "Too large to keep on disk or in git. The catalogue records "
                  "where each one lives.", "",
                  "| Dataset | Location |", "|---|---|"]
        for d in sorted(archived, key=lambda d: d.key):
            lines.append(f"| `{d.key}` | `{d.archived_at}` |")
        lines.append("")

    lines += [
        "## How to check this",
        "",
        "```",
        "python3 scripts/check_consistency.py",
        "```",
        "",
        "Two of the seventeen checks bear on this page: *every catalog path "
        "exists* and *every external dataset cites a source URL*. A dataset "
        "added without a source fails the build rather than appearing here "
        "unattributed.",
        "",
    ]

    OUT.write_text("\n".join(lines))
    print(f"  {len(CATALOG)} datasets across {len(groups)} publishers")
    for name in order:
        print(f"   {name:42} {len(groups[name]):>2}")
    print(f"  wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
