#!/usr/bin/env python3
"""Document the repository layout, generated from what is actually there.

There was no description of the tree anywhere -- README, HANDOFF and
PIPELINE.md all explain parts of the work without saying where things live.
A hand-written map would drift within a week; this one is produced from the
filesystem and the dataset catalogue, so it cannot.

Usage:
  python3 scripts/build_repo_map.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline.datasets import CATALOG  # noqa: E402

OUT = ROOT / "REPO_MAP.md"
SKIP = {".git", ".venv", "node_modules", "__pycache__", ".pytest_cache",
        ".ruff_cache", ".mypy_cache"}

# What each directory is for. A directory present on disk but missing here is
# reported, so the map cannot silently omit new work.
PURPOSE = {
    "cloud": "The chat assistant's Lambda: handler, prompt, tools, and the data bundle it ships with.",
    "data": "Every raw and derived dataset. Large sources are archived to S3; see the catalogue.",
    "infra": "Deployment and infrastructure definitions.",
    "notes": "Working notes, reconnaissance and audits. Not published.",
    "pipeline": "The six-step build: harvest, process, parse federal data, enrich, generate, deploy. `datasets.py` is the catalogue everything else is checked against.",
    "report": "The congressional briefing. One HTML fragment per page under `pages/`, assembled by `generate.py`.",
    "scripts": "One-purpose builders and checkers. Anything catalogued names its script here.",
    "site": "The published site (a symlink into the private repo).",
    "tests": "The suite. Run with `make check` or pytest.",
    "plans": "Design notes written before the work they describe. Historical.",
    "references": "Reference material.",
    "specs": "Specifications.",
}


def du_mb(p: Path) -> float:
    r = subprocess.run(["du", "-sm", str(p)], capture_output=True, text=True)
    try:
        return float(r.stdout.split()[0])
    except Exception:
        return 0.0


def count(p: Path) -> int:
    return sum(1 for x in p.rglob("*")
               if x.is_file() and not any(s in x.parts for s in SKIP))


def main() -> int:
    tops = sorted(p for p in ROOT.iterdir()
                  if p.is_dir() and p.name not in SKIP and not p.name.startswith("."))
    undocumented = [p.name for p in tops if p.name not in PURPOSE]

    lines = [
        "# Repository map",
        "",
        "Generated by `python3 scripts/build_repo_map.py`. Do not edit by hand.",
        "",
        "## Top level",
        "",
        "| Directory | Files | Size | Purpose |",
        "|---|---:|---:|---|",
    ]
    for p in tops:
        n = count(p)
        note = PURPOSE.get(p.name, "**undocumented**")
        if n == 0:
            note += " Currently empty."
        lines.append(f"| `{p.name}/` | {n:,} | {du_mb(p):,.0f} MB | {note} |")

    # data/ deserves its own table: it is the bulk and the least obvious.
    data = ROOT / "data"
    if data.is_dir():
        subs = sorted(p for p in data.iterdir() if p.is_dir() and p.name not in SKIP)
        lines += ["", "## Inside `data/`", "",
                  "| Directory | Files | Size |", "|---|---:|---:|"]
        for p in subs:
            lines.append(f"| `data/{p.name}/` | {count(p):,} | {du_mb(p):,.0f} MB |")

    lines += ["", "## Datasets", "",
              f"{len(CATALOG)} catalogued in `pipeline/datasets.py`. Each names the "
              "script that builds it, what it consumes and produces, its update "
              "cadence, and (for anything external) a source URL. "
              "`scripts/check_consistency.py` fails the build if a catalogued path "
              "is missing or an external dataset has no source URL.",
              "",
              "| Key | Built by | Produces |", "|---|---|---|"]
    for d in sorted(CATALOG, key=lambda x: x.key):
        lines.append(f"| `{d.key}` | `{d.script_rel()}` | "
                     f"{', '.join(f'`{p}`' for p in d.produces[:2])} |")

    lines += ["", "## Regenerating this map", "",
              "    python3 scripts/build_repo_map.py", ""]
    if undocumented:
        lines += ["## Undocumented directories", "",
                  "Present on disk with no entry in `PURPOSE`; add one:", ""]
        lines += [f"- `{n}/`" for n in undocumented]
        lines.append("")

    OUT.write_text("\n".join(lines) + "\n")
    print(f"  {len(tops)} top-level directories, {len(CATALOG)} datasets")
    if undocumented:
        print(f"  UNDOCUMENTED: {', '.join(undocumented)}")
    print(f"  wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
