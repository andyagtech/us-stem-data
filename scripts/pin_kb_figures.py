#!/usr/bin/env python3
"""Propose and verify pins for the knowledge base's volatile figures.

    python3 scripts/pin_kb_figures.py --propose   # emit candidate pins to review
    python3 scripts/pin_kb_figures.py             # verify every pin in place

See cloud/chat/knowledge_pins.py for why pins exist and what they catch that the
other two checks do not.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "site" / "data"
KB = ROOT / "cloud" / "chat" / "knowledge"
sys.path.insert(0, str(ROOT / "cloud" / "chat"))
from knowledge_pins import (NOT_DATA, PINS, PathError, resolve,   # noqa: E402
                            stated_value)
from knowledge_sources import EXTERNAL                              # noqa: E402

FIG = re.compile(r'(?<![\w.,-])(\d{1,3}(?:,\d{3})+|\d+\.\d+|\d{2,})(?![\w.,-])')

#: knowledge file -> the dataset whose rebuild moves its figures.
VOLATILE = {
    "23-the-queue.md": "visa_bulletin",
    "24-enforcement.md": "h1b_enforcement",
    "25-promised-and-queued.md": "lca_wage_levels",
    "26-wages-in-dollars.md": "lca_wage_levels",
    "32-local-wages-and-domestic-series.md": "local_wage_comparison",
    "33-wage-level-trend.md": "wage_level_trend",
    "37-the-body-shops.md": "visa_bodyshops",
}

#: In a list of dicts, the field that names the row. Checked in this order, so a
#: pin reads by_state[state=CA] rather than by_state.0 -- these lists are sorted
#: by volume and an index silently points at a different row after a rebuild.
#: Most-specific first. Order matters and getting it wrong is silent: with
#: "state" ahead of "employer", a top-employers list was keyed
#: top_employers_by_employees[state=CA] -- and several employers are in CA, so
#: the pin read whichever row happened to come first. A selector that matches
#: more than one row is not an identifier, so uniqueness is checked below.
NAME_KEYS = ("employer", "firm", "name", "occupation", "soc", "industry",
             "country", "state", "year", "fiscal_year")


def walk(obj, prefix=""):
    """Every numeric leaf, with a path that uses a selector wherever it can."""
    if isinstance(obj, bool):
        return
    if isinstance(obj, (int, float)):
        yield prefix, float(obj)
        return
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from walk(v, f"{prefix}.{k}" if prefix else str(k))
    elif isinstance(obj, list):
        for i, item in enumerate(obj):
            step = f"[{i}]"
            if isinstance(item, dict):
                siblings = [x for x in obj if isinstance(x, dict)]
                for key in NAME_KEYS:
                    # A year is an identifier even when stored as an int, and
                    # enforcement_intensity has no string key at all -- without
                    # this it would pin by index into a list sorted by year.
                    val = item.get(key)
                    if not isinstance(val, (str, int)) or isinstance(val, bool):
                        continue
                    # Only an identifier if it picks out exactly this row.
                    if sum(1 for x in siblings if x.get(key) == val) != 1:
                        continue
                    step = f"[{key}={val}]"
                    break
            if step.startswith("["):
                base, _, leaf = prefix.rpartition(".")
                sel = f"{leaf}{step}"
                yield from walk(item, f"{base}.{sel}" if base else sel)
            else:
                yield from walk(item, f"{prefix}.{i}")


def propose() -> int:
    print("# Generated by scripts/pin_kb_figures.py --propose. Review before use.")
    total = 0
    skipped: list[tuple[str, str, int]] = []
    for name, stem in sorted(VOLATILE.items()):
        f = DATA / f"{stem}.json"
        if not f.exists():
            print(f"#  !! {stem}.json absent", file=sys.stderr)
            continue
        payload = json.loads(f.read_text())
        index: dict[float, list[str]] = {}
        for path, val in walk(payload):
            index.setdefault(round(val, 4), []).append(path)
        text = (KB / name).read_text()
        print(f"\n    # --- {name} ({stem}) ---")
        seen = set()
        for line in text.splitlines():
            # Only headline figures: a summary-table row or a bolded number.
            if not (line.startswith("|") or "**" in line):
                continue
            words = set(re.findall(r"[A-Za-z][A-Za-z ]{2,}", line))
            for m in FIG.finditer(line):
                raw = m.group(1)
                if raw in EXTERNAL or raw in seen:
                    continue
                if (name, raw) in NOT_DATA:
                    continue
                if re.fullmatch(r"(?:19|20)\d{2}", raw):
                    continue          # a year is a label, not a figure that moves
                v = round(stated_value(raw), 4)
                cands = index.get(v) or index.get(round(v / 100, 4))
                if not cands:
                    continue
                seen.add(raw)

                def score(path: str) -> tuple:
                    """Prefer the row the PROSE LINE is actually about.

                    Several rows can hold the same number: a 1.2-year wait sits
                    under both Philippines and "All chargeability areas". Taking
                    the shortest path picked the wrong one, and a pin that reads
                    the right number from the wrong row passes while telling us
                    nothing. So a path whose own key names appear in the line
                    wins, and ties are left for a human.
                    """
                    segs = re.split(r"[.\[\]=]", path)
                    hit = sum(1 for sg in segs
                              if sg and any(sg.lower() in w.lower() for w in words))
                    return (-hit, path.count("."), "[" not in path, len(path))

                ranked = sorted(cands, key=score)
                best = ranked[0]
                # Unpinnable when the value repeats across many fields and the
                # prose line names none of them: a 2.8-year wait occurs in dozens
                # of months of the bulletin series, and guessing one would pin a
                # right number to an arbitrary row -- which passes forever and
                # proves nothing. Age is not the test; ambiguity is.
                if score(best)[0] == 0 and len(ranked) > 2:
                    skipped.append((name, raw, len(ranked)))
                    continue
                total += 1
                print(f'    ("{name}", "{raw}", "{stem}", "{best}"),')
    print(f"\n#  {total} candidate pins", file=sys.stderr)
    print(f"#  {len(skipped)} skipped as ambiguous (value repeats, prose names no row)",
          file=sys.stderr)
    return 0


def verify() -> int:
    cache: dict[str, object] = {}
    bad, missing = [], []
    for name, written, stem, path in PINS:
        if stem not in cache:
            f = DATA / f"{stem}.json"
            if not f.exists():
                missing.append((name, written, stem, path, "dataset absent"))
                continue
            cache[stem] = json.loads(f.read_text())
        try:
            actual = resolve(cache[stem], path)
        except PathError as exc:
            missing.append((name, written, stem, path, str(exc)))
            continue
        want = stated_value(written)
        if not isinstance(actual, (int, float)):
            missing.append((name, written, stem, path, "not a number"))
            continue
        # The prose may round, and may state a share the data holds as a fraction.
        ok = any(abs(c - float(actual)) <= max(0.051, abs(float(actual)) * 0.0005)
                 for c in (want, want / 100.0, want * 100.0))
        if not ok:
            bad.append((name, written, stem, path, actual))

    print(f"  {len(PINS)} pinned figures, {len(PINS) - len(bad) - len(missing)} matching")
    for name, written, stem, path, actual in bad:
        print(f"    STALE  {name}: prose says {written}, "
              f"{stem}.{path} is now {actual}")
    for name, written, stem, path, why in missing:
        print(f"    BROKEN {name}: {stem}.{path} -- {why}")
    if bad or missing:
        print("  A pinned figure moved. Correct the prose, or repin if the field moved.")
        return 1
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--propose", action="store_true")
    a = ap.parse_args()
    sys.exit(propose() if a.propose else verify())
