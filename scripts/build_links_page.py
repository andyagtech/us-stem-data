#!/usr/bin/env python3
"""LINKS.md: every deployed URL in one place, for sending to people.

WHY THIS IS GENERATED. A hand-kept list of links is wrong the first time a page
is added, renamed or moved, and three pages moved this week alone. This reads
the same navigation the site itself renders -- site/sidebar.js -- so the file
cannot describe a site that does not exist. If a link is in here it is in the
rail, and if it is in the rail it is in here.

WHAT IT DELIBERATELY LEAVES OUT. The private pages, which are declared once in
scripts/private_pages.py. A list of links to hand around is exactly the wrong
place to mention the owner's analytics dashboard, and an earlier version of the
contents page made that mistake.

The URLs carry no .html, because the site does not. The old form still resolves
-- nothing shared before the change broke -- but there is no reason to hand it
out now.

Usage:
    python3 scripts/build_links_page.py
    python3 scripts/build_links_page.py --check     # exit 1 if out of date
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from atomic_write import write_text                          # noqa: E402
from private_pages import is_private                         # noqa: E402

SIDEBAR = ROOT / "site" / "sidebar.js"
SITE_MAP = ROOT / "site" / "data" / "chat" / "site_map.json"
OUT = ROOT / "LINKS.md"
BASE = "https://phd-demographics.andy-barr.com"

SECTION = re.compile(r"\{\s*title:\s*(?:'([^']+)'|\"([^\"]+)\"),\s*items:\s*\[(.*?)\]\s*\}\s*,\s*"
                     r"(?=\{\s*title:|\]\s*;)", re.S)
# Items are split on their own opening brace rather than matched with a
# lookahead for the next one: the lookahead version silently dropped the LAST
# item of every section, which is ten of fifty-three links and exactly the kind
# of quiet omission a generated index exists to prevent.
ITEM_START = re.compile(r"\{\s*href:\s*'([^']+)'\s*,\s*label:\s*(?:'([^']*)'|\"([^\"]*)\")")
ANCHOR = re.compile(r"""\{\s*hash:\s*'([^']+)'\s*,\s*label:\s*(?:'([^']*)'|"([^"]*)")""")


def sections() -> list[tuple[str, list[dict]]]:
    src = SIDEBAR.read_text()
    out = []
    for m in SECTION.finditer(src):
        title = m.group(1) or m.group(2)
        block = m.group(3)
        starts = list(ITEM_START.finditer(block))
        items = []
        for n, it in enumerate(starts):
            tail = block[it.end(): starts[n + 1].start() if n + 1 < len(starts) else len(block)]
            items.append({"href": it.group(1),
                          "label": it.group(2) or it.group(3),
                          "anchors": [{"hash": a.group(1), "label": a.group(2) or a.group(3)}
                                      for a in ANCHOR.finditer(tail)]})
        out.append((title, items))
    return out


def render() -> str:
    secs = sections()
    smap = json.loads(SITE_MAP.read_text()) if SITE_MAP.exists() else {}
    descs = {p["path"]: (p.get("desc") or "") for p in smap.get("pages", [])}

    lines = [
        "# Every link, in one place",
        "",
        f"The deployed site is **{BASE}**.",
        "",
        "Generated by `scripts/build_links_page.py` from the site's own navigation,",
        "so it cannot drift from what is actually deployed. Do not edit by hand.",
        "",
        "URLs carry no `.html`. The older form still works, so anything already",
        "shared keeps resolving, but there is no reason to send it now.",
        "",
    ]

    for title, items in secs:
        visible = [i for i in items
                   if not i["href"].startswith("http") and not is_private(i["href"])]
        if not visible:
            continue
        lines.append(f"## {title}")
        lines.append("")
        for i in visible:
            url = BASE + i["href"]
            desc = descs.get(i["href"], "")
            # One sentence, so the table stays scannable.
            if desc:
                # Keep whole sentences up to a readable length. Cutting at the
                # first full stop dropped the battery page's caveat, which is
                # the sentence that page most needs carried with it.
                desc = desc.replace(" -- ", " — ")
                if len(desc) > 300:
                    kept, out = "", []
                    for part in desc.split(". "):
                        if len(kept) + len(part) > 290 and out:
                            break
                        out.append(part)
                        kept += part + ". "
                    desc = ". ".join(out).rstrip(".") + "."
                desc = desc.rstrip(".")
            lines.append(f"- **[{i['label']}]({url})**" + (f" — {desc}" if desc else ""))
            for a in i["anchors"]:
                lines.append(f"    - [{a['label']}]({url}#{a['hash']})")
        lines.append("")

    external = [(t, i) for t, items in secs for i in items if i["href"].startswith("http")]
    if external:
        lines += ["## Elsewhere", ""]
        lines += [f"- [{i['label']}]({i['href']})" for _t, i in external]
        lines.append("")

    unis = smap.get("universities", [])
    if unis:
        lines += [
            "## University pages",
            "",
            f"One per university, {len(smap.get('university_paths', unis))} of them, at",
            f"`{BASE}/universities/{{key}}`. The first few by non-resident share:",
            "",
        ]
        for u in unis[:10]:
            share = f" — {u['nra']}%" if u.get("nra") is not None else ""
            lines.append(f"- [{u['name']}]({BASE}{u['path']}){share}")
        lines += ["", f"The full list is at [{BASE}/contents]({BASE}/contents).", ""]

    lines += [
        "## If someone checks the numbers",
        "",
        "Every page names the federal source it is built from, and the industry",
        "pages list the CIP codes behind each figure so any number can be",
        "reproduced from IPEDS directly.",
        "",
        "Two limits worth stating up front, because both pages state them too:",
        "the battery page is a proxy this site constructed, since IPEDS",
        "publishes no battery category; and the grid trades counts are a floor,",
        "because IPEDS covers Title IV institutions and misses union and",
        "employer apprenticeships.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if LINKS.md is out of date")
    args = ap.parse_args()
    want = render()
    if args.check:
        have = OUT.read_text() if OUT.exists() else ""
        if have != want:
            print("  LINKS.md is out of date; run scripts/build_links_page.py")
            return 1
        print(f"  LINKS.md is current ({want.count(BASE)} links)")
        return 0
    write_text(OUT, want)
    print(f"  wrote {OUT.relative_to(ROOT)}: {want.count(BASE)} links, "
          f"{len([l for l in want.splitlines() if l.startswith('## ')])} sections")
    return 0


if __name__ == "__main__":
    sys.exit(main())
