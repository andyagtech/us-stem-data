"""
Read-only data access for the chat assistant.

Everything here reads artifacts that are bundled into the Lambda zip under
``chat_data/``.  Nothing is fetched over the network at request time.

    nra_index.csv.gz           1.2 MB, 260,170 rows, year,unitid,cipcode,basis,total,nra
    cip_titles.csv             CIP code -> title
    hd_names.csv               unitid -> institution name, state
    universities_compact.json  per-university digest (see scripts/build_chat_facts.py)
    national_series.json       national time series
    site_map.json              page/anchor registry (contract 4.10)

Loading is lazy per artifact and cached in module globals, so a cold start that
only answers "who made this site?" never pays for the 260k-row parse, while a
warm container pays for it once.

SECURITY NOTE — every string that leaves this module and originates from
scraped repository metadata (department names, institution names, CIP titles)
goes through ``clean_text``.  Callers must treat those values as untrusted
data, never as instructions.
"""
from __future__ import annotations

import csv
import gzip
import json
import os
import re
import sys
from collections import defaultdict

DATA_DIR = os.environ.get(
    "CHAT_DATA_DIR",
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "chat_data"),
)

INDEX_MIN_YEAR = 1995
INDEX_MAX_YEAR = 2025

_index = None          # list[(year, unitid, cip, basis, total, nra)]
_cip_titles = None     # dict cip -> title
_institutions = None   # dict unitid -> (name, state)
_universities = None   # dict key -> digest
_national = None       # dict series -> payload
_site_map = None       # dict


# ---------------------------------------------------------------------------
# untrusted-text hygiene
# ---------------------------------------------------------------------------
_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def clean_text(value, limit: int = 120) -> str:
    """Neutralise scraped free text before it reaches the model or a block.

    Strips control characters (including the ones used to fake role markers),
    collapses whitespace, and hard-caps the length.  It deliberately does NOT
    try to detect "instructions" — that is a losing game; the defence is that
    the caller labels these values as data and the widget renders them with
    textContent.
    """
    if value is None:
        return ""
    s = _CTRL.sub(" ", str(value))
    s = re.sub(r"\s+", " ", s).strip()
    return s[:limit]


def _path(name: str) -> str:
    return os.path.join(DATA_DIR, name)


def available() -> dict:
    """Which artifacts actually made it into the zip.  Used by the health path."""
    return {
        n: os.path.exists(_path(n))
        for n in ("nra_index.csv.gz", "cip_titles.csv", "hd_names.csv",
                  "universities_compact.json", "national_series.json", "site_map.json")
    }


# ---------------------------------------------------------------------------
# loaders
# ---------------------------------------------------------------------------
def load_index():
    """Parse the NRA index once per container.  ~0.2 s, ~70 MB of tuples."""
    global _index
    if _index is None:
        rows = []
        intern = sys.intern
        with gzip.open(_path("nra_index.csv.gz"), "rt", encoding="utf-8") as fh:
            for r in csv.reader(fh):
                if not r or r[0] == "year":
                    continue
                rows.append((int(r[0]), intern(r[1]), intern(r[2]),
                             intern(r[3]), int(r[4]), int(r[5])))
        _index = rows
    return _index


def cip_titles() -> dict:
    global _cip_titles
    if _cip_titles is None:
        out = {}
        p = _path("cip_titles.csv")
        if os.path.exists(p):
            with open(p, encoding="utf-8-sig") as fh:
                for row in csv.DictReader(fh):
                    out[row["cipcode"]] = clean_text(row["title"], 90)
        _cip_titles = out
    return _cip_titles


def institutions() -> dict:
    global _institutions
    if _institutions is None:
        out = {}
        p = _path("hd_names.csv")
        if os.path.exists(p):
            # hd_names.csv is generated by scripts/build_chat_facts.py, which
            # already handles the UTF-8 BOM on the first IPEDS column header.
            with open(p, encoding="utf-8-sig") as fh:
                for row in csv.DictReader(fh):
                    out[row["unitid"]] = (clean_text(row["name"], 80),
                                          clean_text(row.get("state", ""), 2))
        _institutions = out
    return _institutions


def universities() -> dict:
    global _universities
    if _universities is None:
        p = _path("universities_compact.json")
        _universities = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else {}
    return _universities


def national() -> dict:
    global _national
    if _national is None:
        p = _path("national_series.json")
        _national = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else {}
    return _national


def site_map() -> dict:
    global _site_map
    if _site_map is None:
        p = _path("site_map.json")
        _site_map = (json.load(open(p, encoding="utf-8"))
                     if os.path.exists(p) else {"pages": [], "universities": [],
                                                "university_paths": [],
                                                "state_paths": []})
    return _site_map


def site_paths() -> set:
    sm = site_map()
    paths = {p["path"] for p in sm.get("pages", [])}
    paths.update(sm.get("university_paths", []))
    # The 52 state pages are carried as paths rather than scanned entries, to
    # keep them out of the prompt. They are still real destinations, and
    # leaving them out here would make the assistant refuse to link to a page
    # that is live, in the sitemap and on its own hub -- the exact failure
    # /visa-schools and /bodyshops had.
    paths.update(sm.get("state_paths", []))
    paths.update(u["path"] for u in sm.get("universities", []) if u.get("path"))
    return paths


def enumerated_anchors() -> dict:
    """path -> set(ids), only for pages that declare anchors == 'enumerated'."""
    out = {}
    for p in site_map().get("pages", []):
        if p.get("anchors") == "enumerated":
            out[p["path"]] = {s["id"] for s in p.get("sections", [])}
    return out


# ---------------------------------------------------------------------------
# NRA index aggregation — a direct port of scripts/query_nra_index.py
# (load_index / key_for / aggregate / fmt_rows), with the CLI stripped out.
# ---------------------------------------------------------------------------
def _key_for(level, year, unitid, cip, family, pooled):
    code = cip.split(".")[0] if family else cip
    y = "all" if pooled else year
    if level == "national":
        return (y,)
    if level == "subject":
        return (y, code)
    if level == "institution":
        return (y, unitid)
    return (y, unitid, code)


def nra_query(level="cell", cip=None, unitid=None, start=2015, end=INDEX_MAX_YEAR,
              min_total=20, min_share=0.0, pooled=False, family=False,
              sort="share", limit=25, basis=None):
    """Aggregate the NRA index.  Returns (rows, matched_count, meta)."""
    level = level if level in ("national", "subject", "institution", "cell") else "cell"
    cips = [str(c).strip() for c in cip if str(c).strip()] if cip else None
    units = {str(u).strip() for u in unitid if str(u).strip()} if unitid else None
    start = max(INDEX_MIN_YEAR, int(start))
    end = min(INDEX_MAX_YEAR, int(end))
    min_total = max(1, int(min_total))

    agg = defaultdict(lambda: [0, 0])
    for year, uid, code, bas, total, nra in load_index():
        if year < start or year > end:
            continue
        if basis and bas != basis:
            continue
        if cips and not any(code.startswith(c) for c in cips):
            continue
        if units and uid not in units:
            continue
        k = _key_for(level, year, uid, code, family, pooled)
        agg[k][0] += total
        agg[k][1] += nra

    titles, insts = cip_titles(), institutions()
    out = []
    for k, (total, nra) in agg.items():
        if total < min_total:
            continue
        share = nra / total * 100
        if share < min_share:
            continue
        rec = {"year": k[0], "total": total, "nra": nra, "nra_share": round(share, 1)}
        if level == "subject":
            rec["cip"] = k[1]
            rec["subject"] = titles.get(k[1], "(title not in CIP2020 list)")
        elif level == "institution":
            rec["unitid"] = k[1]
            name, st = insts.get(k[1], ("(unknown institution)", ""))
            rec["institution"], rec["state"] = name, st
        elif level == "cell":
            rec["unitid"] = k[1]
            name, st = insts.get(k[1], ("(unknown institution)", ""))
            rec["institution"], rec["state"] = name, st
            rec["cip"] = k[2]
            rec["subject"] = titles.get(k[2], "(title not in CIP2020 list)")
        out.append(rec)

    keys = {"share": lambda r: (-r["nra_share"], -r["total"]),
            "total": lambda r: -r["total"],
            "nra": lambda r: -r["nra"],
            "year": lambda r: (r["year"] if r["year"] != "all" else 0, -r["nra_share"])}
    out.sort(key=keys.get(sort, keys["share"]))
    matched = len(out)
    meta = {"level": level, "start": start, "end": end, "min_total": min_total,
            "pooled": bool(pooled), "family": bool(family), "sort": sort,
            "matched": matched, "returned": min(matched, int(limit))}
    return out[: int(limit)], matched, meta


_STOP = {"and", "or", "of", "the", "in", "for", "a", "an", "&", "other", "general"}


def cip_search(query: str, limit: int = 20) -> list:
    """Find CIP codes by code prefix or by title words.

    Titles in the CIP list rarely read the way a person names a field —
    electrical engineering is "Electrical, Electronics and Communications
    Engineering" — so a plain substring match misses. Match on tokens instead
    and rank whole-phrase hits first, then broader (shorter) codes.
    """
    q = clean_text(query, 60).lower().strip()
    if not q:
        return []
    tokens = [t for t in re.split(r"[^a-z0-9.]+", q) if t and t not in _STOP]
    code_like = bool(re.match(r"^\d{2}(\.\d{0,4})?\.?$", q))
    out = []
    for code, title in cip_titles().items():
        low = title.lower()
        score = None
        if code_like and (code == q.rstrip(".") or code.startswith(q.rstrip("."))):
            score = 0
        elif low.startswith(q):
            score = 1
        elif q in low:
            score = 2
        elif tokens and all(low.startswith(t) for t in tokens[:1]) \
                and all(t in low for t in tokens):
            score = 2
        elif tokens and all(t in low for t in tokens):
            score = 3
        elif tokens and sum(1 for t in tokens if t in low) >= max(1, len(tokens) - 1):
            score = 4
        if score is not None:
            out.append((score, len(code), code, {"cip": code, "title": title}))
    out.sort(key=lambda r: (r[0], r[1], r[2]))
    return [r[3] for r in out[:limit]]


def key_for_unitid(unitid: str):
    """Site university key for an IPEDS unitid, when the site has a page."""
    for key, u in universities().items():
        if str(u.get("unitid")) == str(unitid):
            return key
    return None
