#!/usr/bin/env python3
"""Volatile figures in the knowledge base, pinned to the exact field they came from.

THE THIRD CHECK, and the one for data that MOVES. The other two:

  * knowledge_figures.py re-derives a figure by recomputing it, which proves the
    arithmetic as well as the value. Expensive -- one resolver per figure.
  * check_kb_provenance.py proves a figure is findable SOMEWHERE in a dataset the
    file draws on. Cheap and total, but it cannot tell a stale 70.8% from a
    current one if both happen to appear in the file.

Neither catches the case this does. The DOL disclosure files land quarterly and
the visa bulletin monthly. When they land, every share recomputes. Prose that
said "70.8% promise less than the national median" is then quietly wrong, and
the provenance scan still passes because 70.8 is still a number in the file --
just no longer THAT number.

So a pin names the field: file, the figure as written, and the dotted path that
produced it. The check reads the path and compares. One line per figure, no
resolver to write, and a mismatch names the new value so the prose can be
corrected.

PATH SYNTAX. Dotted, with a selector for list members:

    below_national_median_pct              a top-level field
    series.2025.low_level_pct              nested by key
    by_state[state=California].priced      a list member BY ITS NAME

Always prefer the selector form over an index. The lists here are sorted by
volume, so `by_state.0` silently becomes a different state the moment the
ordering shifts -- and the check would still pass, comparing the right number to
the wrong row.
"""
