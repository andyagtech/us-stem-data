_SELECTOR = re.compile(r"^([A-Za-z0-9_]+)\[([A-Za-z0-9_]+)=(.+)\]$")


class PathError(KeyError):
    """A pinned path no longer exists -- the dataset's shape changed."""


def split_path(path: str) -> list[str]:
    """Split on dots OUTSIDE a [selector].

    Employer names carry dots -- "AMAZON.COM SERVICES LLC", "ERNST & YOUNG U.S.
    LLP", every "INC." -- so a plain path.split(".") tore the selector in half
    and looked for a key called "largest_filers[employer=AMAZON". Seven pins
    failed this way the first time they ran.
    """
    parts, buf, depth = [], [], 0
    for ch in path:
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        if ch == "." and depth == 0:
            parts.append("".join(buf))
            buf = []
            continue
        buf.append(ch)
    parts.append("".join(buf))
    return [p for p in parts if p]


def resolve(data, path: str):
    """Walk a dotted path, honouring [key=value] selectors on lists."""
    node = data
    for part in split_path(path):
        m = _SELECTOR.match(part)
        if m:
            field, key, want = m.groups()
            node = node[field]
            if not isinstance(node, list):
                raise PathError(f"{field} is not a list")
            for item in node:
                if isinstance(item, dict) and str(item.get(key)) == want:
                    node = item
                    break
            else:
                raise PathError(f"no {field} where {key}={want!r}")
            continue
        if isinstance(node, list):
            try:
                node = node[int(part)]
            except (ValueError, IndexError) as exc:
                raise PathError(f"bad list index {part!r}") from exc
        elif isinstance(node, dict):
            if part not in node:
                raise PathError(f"no key {part!r}")
            node = node[part]
        else:
            raise PathError(f"cannot descend into {type(node).__name__} at {part!r}")
    return node


def stated_value(written: str) -> float:
    """The number as the prose writes it: '1,203' or '12.5' or '$85,530'."""
    return float(written.replace(",", "").replace("$", "").rstrip("%"))
